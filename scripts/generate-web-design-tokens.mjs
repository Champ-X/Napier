import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const defaultRepoRoot = path.resolve(path.dirname(scriptPath), "..");
const designPath = "DESIGN.md";
const cssPath = "apps/web/src/styles/tokens.css";
const sourcePattern =
  /<!-- napier-design-tokens:start -->\s*```json\s*([\s\S]*?)```\s*<!-- napier-design-tokens:end -->/;

export function parseDesignTokenSource(markdown) {
  const match = markdown.match(sourcePattern);
  if (!match) {
    throw new Error("DESIGN.md is missing the canonical Napier DTCG JSON block");
  }
  const source = JSON.parse(match[1]);
  if (!source || typeof source !== "object" || Array.isArray(source)) {
    throw new Error("DESIGN.md token source must be a JSON object");
  }
  return source;
}

export function generateWebDesignCss(markdown) {
  const source = parseDesignTokenSource(markdown);
  const tokens = collectTokens(source);
  const definitions = [];
  const seenNames = new Map();

  for (const [tokenPath, token] of tokens) {
    const cssName = cssVariableName(tokenPath);
    if (!cssName) continue;
    const previous = seenNames.get(cssName);
    if (previous) {
      throw new Error(`${cssName} is generated by both ${previous} and ${tokenPath}`);
    }
    seenNames.set(cssName, tokenPath);
    definitions.push([
      cssName,
      formatCssValue(resolveToken(tokenPath, tokens), token.$type, tokenPath),
    ]);
  }

  const required = [
    "--color-bg",
    "--color-fg",
    "--color-fg-muted",
    "--color-surface",
    "--color-border",
    "--color-border-strong",
    "--color-accent",
    "--color-accent-hover",
    "--color-focus-ring",
    "--color-danger",
    "--color-success",
  ];
  const missing = required.filter((name) => !seenNames.has(name));
  if (missing.length > 0) {
    throw new Error(`DESIGN.md is missing generated semantic tokens: ${missing.join(", ")}`);
  }

  definitions.sort(([left], [right]) => left.localeCompare(right));
  const sourceHash = createHash("sha256")
    .update(JSON.stringify(source))
    .digest("hex");
  const variables = definitions.map(([name, value]) => `  ${name}: ${value};`);

  return [
    "/* Generated from DESIGN.md. Do not edit by hand. */",
    `/* source-sha256: ${sourceHash} */`,
    ":root {",
    "  color-scheme: light;",
    ...variables,
    "}",
    "",
    "@media (prefers-contrast: more) {",
    "  :root {",
    "    --color-border: var(--color-border-strong);",
    "    --color-fg-muted: var(--color-fg);",
    "  }",
    "}",
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  *,",
    "  *::before,",
    "  *::after {",
    "    animation-duration: 0.01ms !important;",
    "    transition-duration: 0.01ms !important;",
    "    scroll-behavior: auto !important;",
    "  }",
    "}",
    "",
    "@media (forced-colors: active) {",
    "  :root {",
    "    --color-border-strong: ButtonText;",
    "    --color-focus-ring: Highlight;",
    "  }",
    "  button,",
    "  input,",
    "  select,",
    "  textarea {",
    "    border-color: ButtonText;",
    "  }",
    "  button:focus-visible,",
    "  input:focus-visible,",
    "  select:focus-visible,",
    "  textarea:focus-visible {",
    "    outline: var(--control-focus-width) solid Highlight;",
    "    outline-offset: var(--control-focus-offset);",
    "    box-shadow: none;",
    "  }",
    "}",
    "",
  ].join("\n");
}

function collectTokens(source) {
  const tokens = new Map();
  walk(source, [], tokens);
  return tokens;
}

function walk(value, segments, tokens) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return;
  if (Object.hasOwn(value, "$value")) {
    tokens.set(segments.join("."), value);
    return;
  }
  for (const [key, child] of Object.entries(value)) {
    if (key.startsWith("$")) continue;
    walk(child, [...segments, key], tokens);
  }
}

function resolveToken(tokenPath, tokens, stack = []) {
  if (stack.includes(tokenPath)) {
    throw new Error(`DESIGN.md token alias cycle: ${[...stack, tokenPath].join(" -> ")}`);
  }
  const token = tokens.get(tokenPath);
  if (!token) throw new Error(`DESIGN.md token alias does not exist: ${tokenPath}`);
  const value = token.$value;
  if (typeof value !== "string") return value;
  const alias = value.match(/^\{([\w.-]+)\}$/);
  return alias ? resolveToken(alias[1], tokens, [...stack, tokenPath]) : value;
}

function cssVariableName(tokenPath) {
  const [group, subgroup, ...rest] = tokenPath.split(".");
  const key = [subgroup, ...rest].join("-");
  if (group === "semantic" && subgroup === "color") {
    return `--color-${rest.join("-")}`;
  }
  if (group === "component") {
    return `--${subgroup}-${rest.join("-")}`;
  }
  const prefixes = {
    control: "control",
    duration: "duration",
    ease: "ease",
    font: subgroup === "family" ? "font" : "font-weight",
    inline: "inline",
    inset: "inset",
    layout: "layout",
    radius: "radius",
    shadow: "shadow",
    space: "space",
    stack: "stack",
    type: subgroup === "size" ? "text" : "leading",
  };
  const prefix = prefixes[group];
  if (!prefix) return undefined;
  if (["font", "type"].includes(group)) return `--${prefix}-${rest.join("-")}`;
  return `--${prefix}-${key}`;
}

function formatCssValue(value, type, tokenPath) {
  if (type === "fontFamily") {
    if (!Array.isArray(value)) throw new Error(`${tokenPath} must be a font array`);
    return value.map(formatFontFamily).join(", ");
  }
  if (type === "cubicBezier") {
    if (!Array.isArray(value) || value.length !== 4) {
      throw new Error(`${tokenPath} must be a four-number cubicBezier`);
    }
    return `cubic-bezier(${value.join(", ")})`;
  }
  if (value && typeof value === "object" && !Array.isArray(value)) {
    if (typeof value.value !== "number" || typeof value.unit !== "string") {
      throw new Error(`${tokenPath} has an unsupported composite value`);
    }
    return `${value.value}${value.unit}`;
  }
  if (["string", "number"].includes(typeof value)) return String(value);
  throw new Error(`${tokenPath} has an unsupported token value`);
}

function formatFontFamily(value) {
  return /\s/.test(value) ? JSON.stringify(value) : value;
}

export async function generateWebDesignArtifacts(options = {}) {
  const repoRoot = path.resolve(options.repoRoot ?? defaultRepoRoot);
  const markdown = await readFile(path.join(repoRoot, designPath), "utf8");
  return {
    repoRoot,
    files: new Map([[cssPath, generateWebDesignCss(markdown)]]),
  };
}

async function runCli() {
  const check = process.argv.includes("--check");
  const repoRootFlag = process.argv.indexOf("--repo-root");
  const repoRoot =
    repoRootFlag >= 0 ? process.argv[repoRootFlag + 1] : defaultRepoRoot;
  if (!repoRoot) throw new Error("--repo-root requires a value");
  const generated = await generateWebDesignArtifacts({ repoRoot });

  for (const [relativePath, content] of generated.files) {
    const outputPath = path.join(generated.repoRoot, relativePath);
    if (check) {
      const current = await readFile(outputPath, "utf8").catch(() => "");
      if (current !== content) {
        throw new Error(`${relativePath} is stale; run npm run generate:web-design`);
      }
      continue;
    }
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, content);
    console.log(`Wrote ${relativePath}`);
  }
  if (check) console.log("Generated Web design tokens are current");
}

if (path.resolve(process.argv[1] ?? "") === scriptPath) {
  runCli().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
